import assert from 'node:assert/strict'
import { test } from 'node:test'
import { createElement, type MouseEvent } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import Markdown from 'react-markdown'
import { analysisMarkdownOptions } from '../src/lib/markdown.ts'

function render(text: string) {
  return renderToStaticMarkup(
    createElement(Markdown, { ...analysisMarkdownOptions, children: text }),
  )
}

test('analysis Markdown renders streamed GFM tables with headers, rows and alignment', () => {
  const chunks = [
    '| 항목 | 위험도 | 권장 조치 |\n',
    '| --- | ---: | --- |\n',
    '| 거주 지역 | **높음** | 위치 태그 삭제 |\n',
    '| 연락처 | 보통 | 공개 범위 확인 |\n',
  ]
  let text = ''
  for (const chunk of chunks) {
    text += chunk
    assert.doesNotThrow(() => render(text))
  }
  const html = render(text)
  assert.match(html, /<table>/)
  assert.match(html, /<thead>/)
  assert.match(html, /<th[^>]*>항목<\/th>/)
  assert.match(html, /text-align:right/)
  assert.match(html, /<strong>높음<\/strong>/)
  assert.match(html, /<td>위치 태그 삭제<\/td>/)
  assert.equal((html.match(/<tr>/g) ?? []).length, 3)
})

test('analysis Markdown supports task lists, strikethrough and code without enabling raw HTML', () => {
  const html = render(
    [
      '- [x] 위치 태그 확인',
      '- [ ] 공개 범위 수정',
      '',
      '~~기존 문구~~ `수정 문구`',
      '',
      '```text',
      '이미지 속 주소를 가려주세요.',
      '```',
      '',
      '<script>alert("unsafe")</script>',
      '',
      '[허용하지 않는 링크](javascript:alert(1))',
    ].join('\n'),
  )
  assert.match(html, /type="checkbox"/)
  assert.match(html, /checked=""/)
  assert.match(html, /disabled=""/)
  assert.match(html, /<del>기존 문구<\/del>/)
  assert.match(html, /<code>수정 문구<\/code>/)
  assert.match(html, /<pre><code class="language-text">/)
  assert.doesNotMatch(html, /<script|javascript:/)
})

test('footnote links retain the IDs and accessible descriptions needed for return navigation', () => {
  const html = render('분석 근거입니다.[^1]\n\n[^1]: 공개된 위치 태그')
  assert.match(html, /id="user-content-fnref-1"/)
  assert.match(html, /href="#user-content-fnref-1"/)
  assert.match(html, /data-footnote-ref="true"/)
  assert.match(html, /aria-describedby="footnote-label"/)
  assert.match(html, /aria-label="Back to reference 1"/)
  assert.doesNotMatch(html, /<a[^>]*href="#[^"]*"[^>]*target="_blank"/)
})

test('footnote clicks prevent hash navigation and focus/scroll to the requested target', () => {
  const calls: string[] = []
  const target = {
    tabIndex: 0,
    hasAttribute: () => false,
    focus: () => calls.push('focus'),
    scrollIntoView: () => calls.push('scroll'),
  }
  const link = analysisMarkdownOptions.components.a({
    href: '#user-content-fnref-1',
  })
  const event = {
    button: 0,
    defaultPrevented: false,
    currentTarget: {
      ownerDocument: {
        getElementById: (id: string) => {
          assert.equal(id, 'user-content-fnref-1')
          return target
        },
      },
    },
    preventDefault: () => calls.push('prevent'),
  } as unknown as MouseEvent<HTMLAnchorElement>
  assert.equal(typeof link.props.onClick, 'function')
  link.props.onClick!(event)
  assert.deepEqual(calls, ['prevent', 'focus', 'scroll'])
})

test('Korean footnote names navigate to the percent-encoded IDs generated by GFM', () => {
  const html = render('분석 근거입니다.[^한글]\n\n[^한글]: 공개된 위치 태그')
  const href = html.match(/href="(#[^"]+)"/)![1]
  const id = html.match(/<li id="([^"]+)"/)![1]
  assert.equal(href.slice(1), id)
  assert.match(id, /%ED%95%9C%EA%B8%80/)
  let focused = false
  let scrolled = false
  const target = {
    tabIndex: 0,
    hasAttribute: () => false,
    focus: () => {
      focused = true
    },
    scrollIntoView: () => {
      scrolled = true
    },
  }
  const link = analysisMarkdownOptions.components.a({ href })
  link.props.onClick!({
    button: 0,
    defaultPrevented: false,
    currentTarget: {
      ownerDocument: {
        getElementById: (requested: string) =>
          requested === id ? target : null,
      },
    },
    preventDefault() {},
  } as unknown as MouseEvent<HTMLAnchorElement>)
  assert.equal(focused, true)
  assert.equal(scrolled, true)
})

test('missing or malformed fragments cannot change the analysis route', () => {
  for (const href of ['#missing', '#%E0%A4%A']) {
    let prevented = false
    const link = analysisMarkdownOptions.components.a({ href })
    link.props.onClick!({
      button: 0,
      defaultPrevented: false,
      currentTarget: { ownerDocument: { getElementById: () => null } },
      preventDefault: () => {
        prevented = true
      },
    } as unknown as MouseEvent<HTMLAnchorElement>)
    assert.equal(prevented, true)
  }
})

test('footnotes can focus a list item and remove its temporary tabindex on blur', () => {
  const attributes = new Map<string, string>()
  let onBlur!: () => void
  const calls: string[] = []
  const target = {
    tabIndex: -1,
    hasAttribute: (name: string) => attributes.has(name),
    setAttribute: (name: string, value: string) => attributes.set(name, value),
    removeAttribute: (name: string) => attributes.delete(name),
    addEventListener: (name: string, listener: () => void) => {
      assert.equal(name, 'blur')
      onBlur = listener
    },
    focus: () => calls.push('focus'),
    scrollIntoView: () => calls.push('scroll'),
  }
  const link = analysisMarkdownOptions.components.a({
    href: '#%EA%B0%81%EC%A3%BC',
  })
  link.props.onClick!({
    button: 0,
    defaultPrevented: false,
    currentTarget: {
      ownerDocument: {
        getElementById: (id: string) => {
          assert.equal(id, '각주')
          return target
        },
      },
    },
    preventDefault() {},
  } as unknown as MouseEvent<HTMLAnchorElement>)
  assert.equal(attributes.get('tabindex'), '-1')
  assert.deepEqual(calls, ['focus', 'scroll'])
  onBlur()
  assert.equal(attributes.has('tabindex'), false)
})

test('external links and modified clicks keep normal browser navigation', () => {
  for (const [href, overrides] of [
    ['https://example.com', {}],
    ['#reference', { ctrlKey: true }],
    ['#reference', { metaKey: true }],
    ['#reference', { shiftKey: true }],
    ['#reference', { altKey: true }],
    ['#reference', { button: 1 }],
    ['#reference', { defaultPrevented: true }],
  ] as const) {
    let prevented = false
    const link = analysisMarkdownOptions.components.a({ href })
    link.props.onClick!({
      button: 0,
      defaultPrevented: false,
      preventDefault: () => {
        prevented = true
      },
      ...overrides,
    } as unknown as MouseEvent<HTMLAnchorElement>)
    assert.equal(prevented, false)
    if (href.startsWith('https:')) {
      assert.equal(link.props.target, '_blank')
      assert.equal(link.props.rel, 'noreferrer')
    }
  }
})
